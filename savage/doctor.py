"""Savage Doctor: phone bootstrap, setup, diagnostics and SAFE repair.

Boundary: Doctor only repairs application-level state beneath SAVAGE_AI_ROOT. It never formats,
mounts, resizes or repairs storage, touches block devices, SELinux, boot settings, firewalls or
network ports, escalates privileges, downloads anything, or runs target-affecting actions.
Every repair is an Action marked safe; --yes approves only safe actions.
(Future: 'Build llama.cpp?' / 'Download recommended model?' will be added as separate
explicitly-approved stages; nothing is downloaded in this milestone.)
"""
